import { build } from 'esbuild';
import { parsePath } from 'path-intersection';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(import.meta.dirname, '..');

// Match path-intersection 4.1.0's sampling, including its rounding and short
// curve chords. This runs at build time; the app only contains numeric segments.
// Adapted from path-intersection (MIT), derived from Snap.svg (Apache-2.0).
// See src-tauri/licenses/path-intersection.txt for copyright and license notices.
const fix = (x) => Math.round(x * 1e11) / 1e11;
function derivative(t, a, b, c, d) {
	return t * (t * (-3 * a + 9 * b - 9 * c + 3 * d) + 6 * a - 12 * b + 6 * c) - 3 * a + 3 * b;
}
function curveLength(p) {
	const ts = [-0.1252, 0.1252, -0.3678, 0.3678, -0.5873, 0.5873, -0.7699, 0.7699, -0.9041, 0.9041, -0.9816, 0.9816];
	const cs = [0.2491, 0.2491, 0.2335, 0.2335, 0.2032, 0.2032, 0.1601, 0.1601, 0.1069, 0.1069, 0.0472, 0.0472];
	return (
		ts.reduce((sum, t, i) => {
			const x = derivative(t / 2 + 0.5, p[0], p[2], p[4], p[6]);
			const y = derivative(t / 2 + 0.5, p[1], p[3], p[5], p[7]);
			return sum + cs[i] * Math.sqrt(x * x + y * y);
		}, 0) / 2
	);
}
function point(p, t) {
	const a = 1 - t;
	return [0, 1].map((i) =>
		fix(a ** 3 * p[i] + a ** 2 * 3 * t * p[i + 2] + a * 3 * t * t * p[i + 4] + t ** 3 * p[i + 6])
	);
}
export function segments(path) {
	let start = [0, 0];
	const result = [];
	for (const c of parsePath(path)) {
		if (c[0] === 'M') {
			start = c.slice(1);
			continue;
		}
		if (c[0] !== 'C') throw new Error('Unexpected collider path command');
		const p = [...start, ...c.slice(1)];
		const line = p[0] === p[2] && p[1] === p[3] && p[4] === p[6] && p[5] === p[7];
		const count = line ? 1 : Math.max(1, Math.floor(curveLength(p) / 5));
		for (let i = 0; i < count; i++) result.push([...point(p, i / count), ...point(p, (i + 1) / count)]);
		start = p.slice(6);
	}
	return result;
}

export async function loadVoiceMapSource() {
	const pkg = JSON.parse(await readFile(join(root, 'node_modules/path-intersection/package.json'), 'utf8'));
	if (pkg.version !== '4.1.0') throw new Error('Review native collider sampling before updating path-intersection');
	const bundle = await build({
		absWorkingDir: root,
		stdin: {
			contents:
				"export * from './src/common/ColliderMap'; export * from './src/common/AmongusMap'; export { calculateVoiceAudio, voiceHearingDistance } from './src/renderer/voice/spatialAudio'; export { selectVoiceEffect, shouldApplyRainbowStarEcho } from './src/renderer/voice/voiceEffectRules';export { applyVoiceJamming } from './src/common/VoiceJammingState';export {combineVoiceEffectTunings,getVoiceEffectTuning} from './src/common/VoiceEffectTuning';",
			resolveDir: root,
		},
		bundle: true,
		write: false,
		platform: 'node',
		format: 'esm',
		logLevel: 'warning',
	});
	return import('data:text/javascript;base64,' + Buffer.from(bundle.outputFiles[0].contents).toString('base64'));
}
export async function prepareVoiceMaps({ check = false } = {}) {
	const { colliderMaps, doorMaps } = await loadVoiceMapSource();
	const lines = [
		'// Generated by scripts/tauri-voice-maps.mjs from the pinned release maps.',
		'// Do not edit. SVG coordinates; runtime conversion lives in geometry.rs.',
		'const MAPS: &[Map] = &[',
	];
	const row = (s) => `        [${s.map((x) => (Number.isInteger(x) ? x + '.0' : String(x))).join(', ')}],`;
	for (const map of [0, 1, 2, 4, 5]) {
		lines.push(`    Map { id: ${map}, walls: &[`);
		for (const path of colliderMaps[map]) lines.push(...segments(path).map(row));
		lines.push('    ], doors: &[');
		for (const [id, path] of Object.entries(doorMaps[map] ?? {})) {
			if (!path) continue;
			lines.push(`        Door { id: ${id}, segments: &[`, ...segments(path).map(row), '        ] },');
		}
		lines.push('    ] },');
	}
	lines.push('];', '');
	const content = lines.join('\n');
	const destination = join(root, 'src-tauri/src/voice/maps.generated.rs');
	if (check) {
		if ((await readFile(destination, 'utf8')).replace(/\r\n/g, '\n') !== content)
			throw new Error('Native collider data is stale. Run node scripts/tauri-voice-maps.mjs');
	} else await writeFile(destination, content);
	return { maps: 5, segments: lines.filter((line) => line.startsWith('        [')).length };
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
	console.log(await prepareVoiceMaps({ check: process.argv.includes('--check') }));
